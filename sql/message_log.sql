-- Durable WhatsApp automation queue and delivery log.
-- Run once in the Supabase SQL editor. Server routes use the service-role key;
-- no browser/client policy is intentionally granted.

create table if not exists public.message_log (
  id bigint generated by default as identity primary key,
  event_key text not null unique,
  channel text not null default 'whatsapp',
  template text not null,
  event_type text not null,
  transaction_id text,
  transaction_status text,
  mobile text not null,
  user_id text,
  payload jsonb not null default '{}'::jsonb,
  status text not null default 'queued'
    check (status in ('queued', 'processing', 'sent', 'failed', 'skipped')),
  detail text,
  provider_message_id text,
  attempt_count integer not null default 0,
  next_attempt_at timestamptz not null default now(),
  locked_until timestamptz,
  last_error text,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

