  on public.message_log (status, next_attempt_at, created_at);

alter table public.message_log enable row level security;

-- Atomically claim due messages. SKIP LOCKED prevents two cron requests from
-- processing the same row at the same time. Expired processing leases are
-- recoverable after a worker stops unexpectedly.
create or replace function public.claim_whatsapp_messages(
  p_limit integer default 10,
  p_max_attempts integer default 5,
  p_lock_seconds integer default 120
)
returns setof public.message_log
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  with candidates as (
    select id
    from public.message_log
    where attempt_count < greatest(1, p_max_attempts)
      and next_attempt_at <= now()
      and (
        status in ('queued', 'failed')
        or (status = 'processing' and locked_until < now())
      )
    order by created_at asc
    for update skip locked
    limit least(greatest(1, p_limit), 50)
  )
  update public.message_log as messages
  set status = 'processing',
      attempt_count = messages.attempt_count + 1,
      locked_until = now() + make_interval(secs => greatest(30, p_lock_seconds)),
      updated_at = now()
  from candidates
  where messages.id = candidates.id
  returning messages.*;
end;
$$;

revoke all on function public.claim_whatsapp_messages(integer, integer, integer) from public;
grant execute on function public.claim_whatsapp_messages(integer, integer, integer) to service_role;
